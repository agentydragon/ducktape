"""Small captured-Codex-metadata fixtures for archive integration tests."""

import hashlib
import json
import sqlite3
from pathlib import Path


def index_record(title: str, *, timestamp: str = "2026-01-01T00:00:00Z") -> str:
    return json.dumps({"id": "thread-one", "thread_name": title, "updated_at": timestamp}) + "\n"


def snapshot_sqlite(home: Path, title: str) -> None:
    codex = home / ".codex"
    staging = home / ".local/state/ducktape/ai-session-backup-sqlite"
    image = staging / "images/codex/test-root/state_5.sqlite"
    image.parent.mkdir(parents=True, exist_ok=True)
    image.unlink(missing_ok=True)
    with sqlite3.connect(image) as db:
        db.execute("CREATE TABLE threads (id TEXT, rollout_path TEXT, name TEXT, title TEXT)")
        db.execute(
            "INSERT INTO threads VALUES (?, ?, ?, ?)",
            ("thread-one", str(codex / "sessions/2026/01/thread-one.jsonl"), title, "Autogenerated title"),
        )
    manifest = {
        "version": 1,
        "databases": [
            {
                "harness": "codex",
                "source": str(codex / "state_5.sqlite"),
                "image": "images/codex/test-root/state_5.sqlite",
                "sha256": hashlib.sha256(image.read_bytes()).hexdigest(),
            }
        ],
        "errors": [],
    }
    (staging / "manifest.json").write_text(json.dumps(manifest))


def transcript(home: Path) -> Path:
    path = home / ".codex/sessions/2026/01/thread-one.jsonl"
    path.parent.mkdir(parents=True)
    path.write_text('{"type":"session_meta","payload":{"id":"thread-one"}}\n')
    return path
