"""Managed file output for session_start hook.

Files generated by the session_start hook contain a canary marker. When the
hook finds this marker on a subsequent run, it skips overwriting the file so
that manual edits are preserved. Delete the file to force regeneration.
"""

import configparser
import io
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

CANARY_MARKER = "CANARY:SESSION_START_HOOK"
CANARY_HEADER = (
    f"# {CANARY_MARKER} — Generated by tools/claude_hooks (session_start hook).\n"
    f"# You can edit this file; your changes will be preserved across sessions\n"
    f"# as long as this marker is present. Delete the file to force regeneration.\n"
)


class ConfigConflictError(Exception):
    """Raised when an existing config file conflicts with what we want to write."""


def has_canary(path: Path) -> bool:
    """Check if a file contains the session_start hook canary marker."""
    return path.exists() and CANARY_MARKER in path.read_text()


def add_canary(content: str) -> str:
    """Insert canary header into content, respecting shebangs."""
    if content.startswith("#!"):
        first_newline = content.index("\n") + 1
        return content[:first_newline] + CANARY_HEADER + content[first_newline:]
    return CANARY_HEADER + content


def write_config(path: Path, content: str, description: str, *, canary: bool = True) -> None:
    """Write config file conservatively with canary support.

    Accepts:
    - File doesn't exist: create it (with canary header if canary=True)
    - File exists with canary: skip (user may have edited it)
    - File exists with exact same content: no-op (idempotent)

    Rejects:
    - File exists with different content and no canary: raises ConfigConflictError

    Args:
        canary: Prepend canary header (use False for formats like JSON that don't support comments).
    """
    full_content = add_canary(content) if canary else content
    if path.exists():
        if has_canary(path):
            logger.debug("Skipping %s (canary marker present)", path)
            return
        existing = path.read_text()
        if existing == full_content:
            logger.debug("Config %s already has expected content", path)
            return
        raise ConfigConflictError(
            f"Existing {description} at {path} has unexpected content. "
            f"Expected our config but found different content. "
            f"Delete the file to allow reconfiguration: rm {path}"
        )
    path.write_text(full_content)
    logger.debug("Wrote %s to %s", description, path)


def write_ini_config(path: Path, config: configparser.ConfigParser, description: str) -> None:
    """Write a ConfigParser as a canary-protected INI file."""
    buf = io.StringIO()
    config.write(buf)
    write_config(path, buf.getvalue(), description)
