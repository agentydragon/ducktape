-- +goose Up
-- Fresh databases create the current schema; completed migration 17 is adopted without rewriting data.
-- +goose StatementBegin
DO $history_baseline$
DECLARE
    latest_version BIGINT;
BEGIN
    SELECT COALESCE(max(version_id) FILTER (WHERE is_applied),0) INTO latest_version
    FROM (SELECT DISTINCT ON (version_id) version_id,is_applied
          FROM history_service_goose_version ORDER BY version_id,id DESC) AS latest;
    IF latest_version=17 AND NOT EXISTS (SELECT 1 FROM history_service_goose_version WHERE version_id>17) THEN
        IF (SELECT count(*) FROM information_schema.tables WHERE table_schema=current_schema()
            AND table_type='BASE TABLE' AND table_name IN ('session_history','session_event','session_event_settlement','session_event_settled_range','session_event_removed_range','session_projection_lease','thread_checkpoint','thread_history_summary','thread_entity','thread_evidence','thread_native_link','thread_payload_manifest','thread_payload_chunk','session_fold_pending','session_event_block')) <> 15
           OR EXISTS (
            SELECT 1 FROM (VALUES ('session_history','recorded_position','bigint','NO'),
            ('session_history','writer_identity_uid','character varying','YES'),
            ('session_history','execution_identity_uid','character varying','YES'),
            ('session_event','compactable','boolean','NO'),
            ('session_event_block','cursors','ARRAY','NO'),
            ('session_event_block','sizes','ARRAY','NO'),
            ('session_event_block','payload','bytea','NO'),
            ('thread_entity','state','jsonb','NO'),
            ('thread_entity','entity_index','bigint','NO')) AS expected(table_name,column_name,data_type,is_nullable)
            WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns actual
                WHERE actual.table_schema=current_schema() AND actual.table_name=expected.table_name
                  AND actual.column_name=expected.column_name AND actual.data_type=expected.data_type
                  AND actual.is_nullable=expected.is_nullable))
           OR (NOT EXISTS (SELECT 1 FROM pg_index WHERE indexrelid=to_regclass('ix_session_event_compactable_cursor') AND indisvalid)
            OR (SELECT count(*) FROM pg_trigger WHERE tgrelid='session_history'::regclass AND NOT tgisinternal
                AND tgname IN ('session_history_fold_pending_insert','session_history_fold_pending_update'))<>2
            OR NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname='electric_publication_agentplane_history')) THEN
            RAISE EXCEPTION 'history baseline predecessor has an unrecognized schema; repair migration 17 before adoption';
        END IF;
        RETURN;
    END IF;
    IF latest_version<>0 OR EXISTS (SELECT 1 FROM history_service_goose_version WHERE version_id>0) THEN
        RAISE EXCEPTION 'history baseline requires a fresh database or completed audit rewrite migration 17; run the previous image with writers stopped first';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_class WHERE relnamespace=current_schema()::regnamespace
        AND relkind IN ('r','p','v','m','S','f')
        AND relname NOT IN ('history_service_goose_version','history_service_goose_version_id_seq')) THEN
        RAISE EXCEPTION 'history database has unrecognized objects without migration history';
    END IF;
    CREATE TABLE session_history (
        id UUID PRIMARY KEY,
        source_id VARCHAR,
        last_cursor BIGINT NOT NULL,
        feed_state BYTEA,
        writer_namespace VARCHAR,
        writer_name VARCHAR,
        writer_uid VARCHAR,
        writer_identity_name VARCHAR,
        writer_identity_uid VARCHAR,
        recorded_position BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        sandbox_uid VARCHAR,
        execution_principal_namespace VARCHAR,
        execution_principal_name VARCHAR,
        execution_principal_uid VARCHAR,
        execution_identity_name VARCHAR,
        execution_identity_uid VARCHAR,
        sandbox_namespace VARCHAR,
        sandbox_name VARCHAR,
        CONSTRAINT history_last_cursor_nonnegative CHECK (last_cursor >= 0),
        CONSTRAINT history_writer_complete CHECK (num_nulls(writer_namespace, writer_name, writer_uid) IN (0, 3)),
        CONSTRAINT history_writer_identity_complete CHECK (num_nulls(writer_identity_name, writer_identity_uid) IN (0, 2)),
        CONSTRAINT history_writer_one_kind CHECK (writer_uid IS NULL OR writer_identity_uid IS NULL),
        CONSTRAINT history_sandbox_complete CHECK (num_nulls(sandbox_namespace, sandbox_name) IN (0, 2)),
        CONSTRAINT history_execution_principal_complete CHECK (num_nulls(execution_principal_namespace, execution_principal_name, execution_principal_uid) IN (0, 3)),
        CONSTRAINT history_execution_identity_complete CHECK (num_nulls(execution_identity_name, execution_identity_uid) IN (0, 2))
    );
    CREATE UNIQUE INDEX ux_history_recorded_position ON session_history (recorded_position);
    CREATE INDEX ix_history_execution_principal_recorded
        ON session_history (execution_principal_namespace, execution_principal_name, execution_principal_uid, recorded_position);
    CREATE INDEX ix_history_execution_identity_recorded
        ON session_history (execution_identity_name, execution_identity_uid, recorded_position)
        WHERE execution_identity_uid IS NOT NULL;

    CREATE TABLE session_event (
        session_id UUID NOT NULL REFERENCES session_history (id),
        cursor BIGINT NOT NULL,
        payload BYTEA NOT NULL,
        kind INTEGER NOT NULL,
        PRIMARY KEY (session_id, cursor)
    );

    CREATE INDEX ix_session_event_kind_cursor ON session_event (session_id, kind, cursor);

    CREATE TABLE session_event_settlement (
        session_id UUID NOT NULL REFERENCES session_history (id),
        completion_cursor BIGINT NOT NULL,
        payload BYTEA NOT NULL,
        PRIMARY KEY (session_id, completion_cursor)
    );

    CREATE TABLE session_event_settled_range (
        session_id UUID NOT NULL,
        first_cursor BIGINT NOT NULL,
        last_cursor BIGINT NOT NULL,
        completion_cursor BIGINT NOT NULL,
        PRIMARY KEY (session_id, first_cursor),
        CONSTRAINT settled_range_ordered CHECK (first_cursor <= last_cursor),
        CONSTRAINT settled_range_settlement FOREIGN KEY (session_id, completion_cursor)
            REFERENCES session_event_settlement (session_id, completion_cursor)
    );

    CREATE TABLE session_event_removed_range (
        session_id UUID NOT NULL REFERENCES session_history (id),
        first_cursor BIGINT NOT NULL,
        last_cursor BIGINT NOT NULL,
        PRIMARY KEY (session_id, first_cursor),
        CONSTRAINT removed_range_ordered CHECK (first_cursor <= last_cursor)
    );

    CREATE TABLE session_projection_lease (
        session_id UUID PRIMARY KEY,
        token UUID NOT NULL,
        expires_at TIMESTAMPTZ NOT NULL
    );

    CREATE TABLE thread_checkpoint (
        thread_id UUID PRIMARY KEY,
        source_id TEXT,
        projection_epoch TEXT NOT NULL,
        through_cursor BIGINT NOT NULL,
        CONSTRAINT thread_checkpoint_source_prefix CHECK (source_id IS NOT NULL OR through_cursor = 0)
    );

    CREATE TABLE thread_history_summary (
        thread_id UUID PRIMARY KEY,
        last_event_at TIMESTAMPTZ,
        last_turn_status BIGINT,
        attached JSONB,
        "end" JSONB,
        last_model_activity_at TIMESTAMPTZ,
        first_event_at TIMESTAMPTZ,
        idle_since TIMESTAMPTZ
    );
    CREATE INDEX ix_thread_history_summary_first_event
        ON thread_history_summary (first_event_at, thread_id);

    CREATE TABLE thread_entity (
        thread_id UUID NOT NULL,
        projection_epoch TEXT NOT NULL,
        entity_kind TEXT NOT NULL,
        entity_id TEXT NOT NULL,
        cursor BIGINT NOT NULL,
        revision_cursor BIGINT NOT NULL,
        pending BOOLEAN NOT NULL,
        state JSONB NOT NULL,
        entity_index BIGINT NOT NULL,
        PRIMARY KEY (thread_id, projection_epoch, entity_kind, entity_id)
    );
    CREATE INDEX ix_thread_entity_scope_cursor
        ON thread_entity (thread_id, projection_epoch, cursor, entity_kind, entity_id);
    CREATE UNIQUE INDEX ix_thread_entity_scope_entity_index
        ON thread_entity (thread_id, projection_epoch, entity_index);
    CREATE INDEX ix_thread_entity_scope_pending_cursor
        ON thread_entity (thread_id, projection_epoch, cursor, entity_kind, entity_id) WHERE pending;
    CREATE INDEX ix_thread_entity_scope_revision
        ON thread_entity (thread_id, projection_epoch, revision_cursor);
    CREATE INDEX ix_thread_entity_scope_segment_cursor
        ON thread_entity (thread_id, projection_epoch, cursor)
        WHERE entity_kind IN ('item', 'confirmed_input', 'lifecycle');

    CREATE TABLE thread_evidence (
        thread_id UUID NOT NULL,
        projection_epoch TEXT NOT NULL,
        entity_cursor BIGINT NOT NULL,
        observation_cursor BIGINT NOT NULL,
        PRIMARY KEY (thread_id, projection_epoch, entity_cursor, observation_cursor)
    );

    CREATE TABLE thread_native_link (
        thread_id UUID NOT NULL,
        projection_epoch TEXT NOT NULL,
        entity_cursor BIGINT NOT NULL,
        observation_cursor BIGINT NOT NULL,
        source_sequence BIGINT NOT NULL,
        PRIMARY KEY (thread_id, projection_epoch, entity_cursor, observation_cursor, source_sequence)
    );

    CREATE TABLE thread_payload_manifest (
        thread_id UUID NOT NULL,
        projection_epoch TEXT NOT NULL,
        owner_cursor BIGINT NOT NULL,
        owner_id TEXT NOT NULL,
        field TEXT NOT NULL,
        generation BIGINT NOT NULL,
        revision_cursor BIGINT NOT NULL,
        chunk_count BIGINT NOT NULL,
        content_bytes BIGINT NOT NULL,
        PRIMARY KEY (thread_id, projection_epoch, owner_cursor, owner_id, field, generation, revision_cursor)
    );

    CREATE TABLE thread_payload_chunk (
        thread_id UUID NOT NULL,
        projection_epoch TEXT NOT NULL,
        owner_cursor BIGINT NOT NULL,
        owner_id TEXT NOT NULL,
        field TEXT NOT NULL,
        generation BIGINT NOT NULL,
        chunk_index BIGINT NOT NULL,
        text JSON NOT NULL,
        PRIMARY KEY (thread_id, projection_epoch, owner_cursor, owner_id, field, generation, chunk_index)
    );

    CREATE SEQUENCE session_fold_pending_version;
    CREATE TABLE session_fold_pending (
        session_id UUID PRIMARY KEY REFERENCES session_history (id) ON DELETE CASCADE,
        version BIGINT NOT NULL
    );
    CREATE FUNCTION mark_session_fold_pending() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
        INSERT INTO session_fold_pending (session_id, version)
            VALUES (NEW.id, nextval('session_fold_pending_version'))
            ON CONFLICT (session_id) DO UPDATE SET version = EXCLUDED.version;
        RETURN NULL;
    END $$;
    CREATE TRIGGER session_history_fold_pending_insert AFTER INSERT ON session_history
        FOR EACH ROW EXECUTE FUNCTION mark_session_fold_pending();
    CREATE TRIGGER session_history_fold_pending_update AFTER UPDATE OF last_cursor, feed_state ON session_history
        FOR EACH ROW WHEN (OLD.last_cursor IS DISTINCT FROM NEW.last_cursor OR OLD.feed_state IS DISTINCT FROM NEW.feed_state)
        EXECUTE FUNCTION mark_session_fold_pending();

    -- Electric replicates these four tables. The `electric` role is the cluster's replication login.
    ALTER TABLE thread_checkpoint REPLICA IDENTITY FULL;
    ALTER TABLE thread_entity REPLICA IDENTITY FULL;
    ALTER TABLE thread_payload_manifest REPLICA IDENTITY FULL;
    ALTER TABLE thread_payload_chunk REPLICA IDENTITY FULL;
    GRANT USAGE ON SCHEMA public TO electric;
    GRANT SELECT ON thread_checkpoint, thread_entity, thread_payload_manifest, thread_payload_chunk TO electric;
    DO $$
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'electric_publication_agentplane_history') THEN
            CREATE PUBLICATION electric_publication_agentplane_history
                FOR TABLE thread_checkpoint, thread_entity, thread_payload_manifest, thread_payload_chunk;
        END IF;
    END $$;
    ALTER TABLE session_event ADD COLUMN compactable BOOLEAN NOT NULL DEFAULT FALSE;
    CREATE INDEX ix_session_event_compactable_cursor ON session_event (session_id, kind, cursor) WHERE compactable;

    CREATE TABLE session_event_block (
        session_id UUID NOT NULL REFERENCES session_history (id),
        first_cursor BIGINT NOT NULL,
        last_cursor BIGINT NOT NULL,
        kind INTEGER NOT NULL,
        cursors BIGINT[] NOT NULL,
        sizes INTEGER[] NOT NULL,
        payload BYTEA NOT NULL,
        PRIMARY KEY (session_id, first_cursor),
        CHECK (first_cursor > 0 AND last_cursor >= first_cursor),
        CHECK (cardinality(cursors) BETWEEN 1 AND 256),
        CHECK (cardinality(cursors) = cardinality(sizes)),
        CHECK (cursors[1] = first_cursor AND cursors[cardinality(cursors)] = last_cursor)
    );
    CREATE INDEX ix_session_event_block_kind_first ON session_event_block (session_id, kind, first_cursor);
    CREATE INDEX ix_session_event_block_kind_last ON session_event_block (session_id, kind, last_cursor);
END
$history_baseline$;
