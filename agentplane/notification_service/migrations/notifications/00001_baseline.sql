CREATE TABLE IF NOT EXISTS inbox (
    id UUID PRIMARY KEY,
    owner_namespace VARCHAR NOT NULL,
    owner_name VARCHAR NOT NULL,
    destination_key VARCHAR NOT NULL,
    destination_ref JSONB NOT NULL,
    session_id VARCHAR NOT NULL,
    last_cursor BIGINT NOT NULL,
    acknowledged BIGINT NOT NULL,
    covered BIGINT NOT NULL,
    expired_through BIGINT NOT NULL,
    retired BOOLEAN NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    next_attempt TIMESTAMPTZ,
    claim UUID,
    claim_until TIMESTAMPTZ NOT NULL,
    delivery_error VARCHAR,
    stale_check_at TIMESTAMPTZ,
    UNIQUE (owner_namespace, owner_name, destination_key)
);
CREATE INDEX IF NOT EXISTS ix_inbox_next_attempt ON inbox (next_attempt);

CREATE TABLE IF NOT EXISTS github_installation (
    app_id BIGINT NOT NULL,
    installation_id BIGINT NOT NULL,
    generation BIGINT NOT NULL,
    PRIMARY KEY (app_id, installation_id)
);

-- BIGSERIAL, not a plain BIGINT: Alembic built the key with a sequence default that the code never
-- uses (repository ids come from GitHub). Dropping it is a schema change, not a baseline.
CREATE TABLE IF NOT EXISTS github_repository (
    repository_id BIGSERIAL PRIMARY KEY,
    full_name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS github_repository_access (
    app_id BIGINT NOT NULL,
    installation_id BIGINT NOT NULL,
    repository_id BIGINT NOT NULL REFERENCES github_repository (repository_id),
    generation BIGINT NOT NULL,
    validated_installation_generation BIGINT,
    checked_at TIMESTAMPTZ,
    valid_until TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    error_kind VARCHAR,
    error VARCHAR,
    error_since TIMESTAMPTZ,
    error_observed_at TIMESTAMPTZ,
    next_attempt TIMESTAMPTZ,
    claim UUID,
    claim_until TIMESTAMPTZ,
    PRIMARY KEY (app_id, installation_id, repository_id),
    FOREIGN KEY (app_id, installation_id) REFERENCES github_installation (app_id, installation_id),
    CONSTRAINT github_access_error_kind CHECK (
        error_kind IN ('rate_limited', 'unavailable', 'access_denied', 'source_changed', 'processing_error')),
    CONSTRAINT github_access_error_state CHECK (
        (error IS NULL AND error_kind IS NULL AND error_since IS NULL AND error_observed_at IS NULL) OR
        (error IS NOT NULL AND error_kind IS NOT NULL AND error_since IS NOT NULL AND error_observed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS github_subject (
    repository_id BIGINT NOT NULL REFERENCES github_repository (repository_id),
    kind VARCHAR NOT NULL,
    subject_key VARCHAR NOT NULL,
    generation BIGINT NOT NULL,
    last_success_at TIMESTAMPTZ,
    error_kind VARCHAR,
    error VARCHAR,
    error_since TIMESTAMPTZ,
    error_observed_at TIMESTAMPTZ,
    next_attempt TIMESTAMPTZ,
    claim UUID,
    claim_until TIMESTAMPTZ,
    PRIMARY KEY (repository_id, kind, subject_key),
    CONSTRAINT github_subject_error_kind CHECK (
        error_kind IN ('rate_limited', 'unavailable', 'access_denied', 'source_changed', 'processing_error')),
    CONSTRAINT github_subject_error_state CHECK (
        (error IS NULL AND error_kind IS NULL AND error_since IS NULL AND error_observed_at IS NULL) OR
        (error IS NOT NULL AND error_kind IS NOT NULL AND error_since IS NOT NULL AND error_observed_at IS NOT NULL)),
    CONSTRAINT github_subject_kind CHECK (kind IN ('pull_request', 'issue', 'branch', 'commit'))
);

CREATE TABLE IF NOT EXISTS github_subject_revision (
    repository_id BIGINT NOT NULL,
    kind VARCHAR NOT NULL,
    subject_key VARCHAR NOT NULL,
    head_repository_id BIGINT NOT NULL REFERENCES github_repository (repository_id),
    sha VARCHAR NOT NULL,
    PRIMARY KEY (repository_id, kind, subject_key, head_repository_id, sha),
    FOREIGN KEY (repository_id, kind, subject_key) REFERENCES github_subject (repository_id, kind, subject_key)
);

CREATE TABLE IF NOT EXISTS github_delivery (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id BIGINT NOT NULL,
    delivery_id UUID NOT NULL,
    installation_id BIGINT NOT NULL,
    repository_id BIGINT,
    event VARCHAR NOT NULL,
    action VARCHAR,
    head_sha VARCHAR,
    digest BYTEA NOT NULL,
    payload JSONB NOT NULL,
    UNIQUE (app_id, delivery_id),
    CONSTRAINT github_delivery_position_repository UNIQUE (position, repository_id)
);
CREATE INDEX IF NOT EXISTS ix_github_delivery_repository_id ON github_delivery (repository_id);
CREATE INDEX IF NOT EXISTS ix_github_delivery_head ON github_delivery (app_id, repository_id, head_sha);

CREATE TABLE IF NOT EXISTS github_delivery_subject (
    delivery_position BIGINT NOT NULL,
    repository_id BIGINT NOT NULL,
    kind VARCHAR NOT NULL,
    subject_key VARCHAR NOT NULL,
    PRIMARY KEY (delivery_position, repository_id, kind, subject_key),
    FOREIGN KEY (delivery_position, repository_id)
        REFERENCES github_delivery (position, repository_id) ON DELETE CASCADE,
    FOREIGN KEY (repository_id, kind, subject_key) REFERENCES github_subject (repository_id, kind, subject_key)
);
CREATE INDEX IF NOT EXISTS ix_github_delivery_subject_lookup
    ON github_delivery_subject (repository_id, kind, subject_key, delivery_position);

CREATE TABLE IF NOT EXISTS subscription (
    id UUID PRIMARY KEY,
    inbox_id UUID NOT NULL REFERENCES inbox (id) ON DELETE CASCADE,
    idempotency_key VARCHAR NOT NULL,
    creation JSONB NOT NULL,
    version INTEGER NOT NULL,
    actions_after_sequence BIGINT,
    cancelled BOOLEAN NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    next_attempt TIMESTAMPTZ,
    error VARCHAR,
    generation BIGINT NOT NULL,
    github_start_position BIGINT,
    last_success_at TIMESTAMPTZ,
    error_kind VARCHAR,
    error_since TIMESTAMPTZ,
    error_observed_at TIMESTAMPTZ,
    github_app_id BIGINT,
    github_installation_id BIGINT,
    github_repository_id BIGINT,
    github_subject_kind VARCHAR,
    github_subject_key VARCHAR,
    UNIQUE (inbox_id, idempotency_key),
    CONSTRAINT subscription_github_access FOREIGN KEY (github_app_id, github_installation_id, github_repository_id)
        REFERENCES github_repository_access (app_id, installation_id, repository_id),
    CONSTRAINT subscription_github_subject FOREIGN KEY (github_repository_id, github_subject_kind, github_subject_key)
        REFERENCES github_subject (repository_id, kind, subject_key),
    CONSTRAINT subscription_creation_source CHECK (creation ? 'source'),
    CONSTRAINT subscription_error_kind CHECK (
        error_kind IN ('rate_limited', 'unavailable', 'access_denied', 'source_changed', 'processing_error')),
    CONSTRAINT subscription_error_state CHECK (
        (error IS NULL AND error_kind IS NULL AND error_since IS NULL AND error_observed_at IS NULL) OR
        (error IS NOT NULL AND error_kind IS NOT NULL AND error_since IS NOT NULL AND error_observed_at IS NOT NULL)),
    CONSTRAINT subscription_source_state CHECK (
        CASE creation #>> '{source,provider}'
            WHEN 'actions' THEN actions_after_sequence IS NOT NULL AND github_start_position IS NULL
                AND github_app_id IS NULL AND github_installation_id IS NULL AND github_repository_id IS NULL
                AND github_subject_kind IS NULL AND github_subject_key IS NULL
            WHEN 'github' THEN actions_after_sequence IS NULL AND github_start_position IS NOT NULL
                AND github_app_id IS NOT NULL AND github_installation_id IS NOT NULL
                AND github_repository_id IS NOT NULL
                AND github_subject_kind IS NOT NULL AND github_subject_key IS NOT NULL
            ELSE false
        END)
);

CREATE TABLE IF NOT EXISTS entry (
    inbox_id UUID NOT NULL REFERENCES inbox (id) ON DELETE CASCADE,
    cursor BIGINT NOT NULL,
    event JSONB NOT NULL,
    payload JSONB,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (inbox_id, cursor),
    UNIQUE (inbox_id, event)
);

CREATE TABLE IF NOT EXISTS subscription_match (
    subscription_id UUID NOT NULL REFERENCES subscription (id) ON DELETE CASCADE,
    cursor BIGINT NOT NULL,
    PRIMARY KEY (subscription_id, cursor)
);

CREATE TABLE IF NOT EXISTS notice (
    inbox_id UUID PRIMARY KEY REFERENCES inbox (id) ON DELETE CASCADE,
    command_id UUID NOT NULL,
    through_cursor BIGINT NOT NULL,
    text VARCHAR NOT NULL,
    attempted BOOLEAN NOT NULL,
    admitted BOOLEAN NOT NULL,
    confirmed BOOLEAN NOT NULL,
    error VARCHAR,
    runner_cursor BIGINT NOT NULL,
    runner_entry BYTEA
);
