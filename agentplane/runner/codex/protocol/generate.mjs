import { readFile, writeFile } from "node:fs/promises";
import { InputData, JSONSchemaInput, quicktype } from "quicktype-core";

const [schemaPath, outputPath] = process.argv.slice(2);
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const input = new JSONSchemaInput();
// Select consumed protocol types; their fields and dependencies stay upstream-owned.
const roots = [
  "InitializeParams",
  "ThreadStartParams",
  "ThreadStartResponse",
  "ThreadResumeParams",
  "ThreadResumeResponse",
  "ThreadItemsListParams",
  "ThreadItemsListResponse",
  "TurnStartParams",
  "TurnStartResponse",
  "TurnInterruptParams",
  "TurnStartedNotification",
  "TurnCompletedNotification",
  "AgentMessageDeltaNotification",
  "ReasoningSummaryTextDeltaNotification",
  "CommandExecutionOutputDeltaNotification",
];
const properties = {};
for (const name of roots) {
  if (!schema.definitions[name]) throw new Error(`Missing Codex schema: ${name}`);
  properties[name] = { $ref: `#/definitions/${name}` };
}

for (const [name, kind] of [
  ["AgentMessageItem", "agentMessage"],
  ["ReasoningItem", "reasoning"],
  ["CommandExecutionItem", "commandExecution"],
  ["SubAgentActivityItem", "subAgentActivity"],
]) {
  const definition = "ThreadItem";
  const index = schema.definitions[definition].oneOf.findIndex((variant) => variant.properties.type.enum?.[0] === kind);
  if (index === -1) throw new Error(`Missing Codex ${definition} variant: ${kind}`);
  properties[name] = { $ref: `#/definitions/${definition}/oneOf/${index}` };
}

await input.addSource({
  name: "Protocol",
  schema: JSON.stringify({ type: "object", properties, definitions: schema.definitions }),
});

const inputData = new InputData();
inputData.addInput(input);
const result = await quicktype({
  inputData,
  lang: "go",
  combineClasses: false,
  rendererOptions: { package: "protocol", "omit-empty": true },
});
await writeFile(
  outputPath,
  `// Code generated by quicktype from the pinned Codex schema. DO NOT EDIT.\n\n${result.lines.join("\n")}\n`
);
