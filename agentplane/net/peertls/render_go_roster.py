"""Render the Go service-identity roster (`service_identities.go`) from the one in `config.py`."""

import re
import sys

from agentplane.net.peertls import config

PREFIX = "spiffe://agentplane/"
GO_ACRONYMS = {"llm": "LLM", "mcp": "MCP"}


def go_name(path: str) -> str:
    return "".join(GO_ACRONYMS.get(word, word.capitalize()) for word in path.split("-")) + "URI"


def roster() -> dict[str, str]:
    """Constant name to URI, after checking each is named for its path and holds exactly one role."""
    uris = {name: value for name, value in vars(config).items() if re.fullmatch(r"[A-Z0-9_]+_URI", name)}
    for name, uri in uris.items():
        path = uri.removeprefix(PREFIX)
        if not re.fullmatch(r"[a-z]+(-[a-z]+)*", path) or name != path.upper().replace("-", "_") + "_URI":
            raise ValueError(f"{name}={uri!r} must be {PREFIX}<path> named <PATH>_URI")
    roles = (config.WORKLOAD_SERVER_URIS, config.RUNNER_CONTROL_SERVER_URIS, config.CLIENT_ONLY_URIS)
    for uri in uris.values():
        if sum(uri in role for role in roles) != 1:
            raise ValueError(f"{uri=} must be in exactly one role set")
    if unnamed := config.SERVICE_URIS - set(uris.values()):
        raise ValueError(f"role sets name URIs without a constant: {sorted(unnamed)}")
    return uris


def switch(func: str, doc: str, uris: frozenset[str]) -> str:
    cases = ",\n\t\t".join(go_name(uri.removeprefix(PREFIX)) for uri in sorted(uris))
    return f"""
// {doc}
func {func}(uri string) bool {{
\tswitch uri {{
\tcase {cases}:
\t\treturn true
\tdefault:
\t\treturn false
\t}}
}}
"""


def render() -> str:
    uris = roster()
    width = max(len(go_name(uri.removeprefix(PREFIX))) for uri in uris.values())
    constants = "".join(f'\t{go_name(uri.removeprefix(PREFIX)):<{width}} = "{uri}"\n' for uri in sorted(uris.values()))
    return (
        "// Code generated by //agentplane/net/peertls:service_identities_go from config.py. DO NOT EDIT.\n\n"
        "package peertls\n\n"
        "// The fixed first-party service identities; `config.py` documents each and its role.\n"
        f"const (\n{constants})\n"
        + switch(
            "IsServiceURI",
            "IsServiceURI accepts the fixed first-party service identities. Workload credential\n"
            "// URIs have a separate grammar and are never service identities.",
            config.SERVICE_URIS,
        )
        + switch(
            "isWorkloadServiceURI",
            "isWorkloadServiceURI accepts identities serving a workload-CA listener.",
            config.WORKLOAD_SERVER_URIS,
        )
        + switch(
            "isServerURI", "isServerURI accepts the identities a ClientTLS may pin as its server.", config.SERVER_URIS
        )
    )


def main() -> None:
    sys.stdout.write(render())


if __name__ == "__main__":
    main()
