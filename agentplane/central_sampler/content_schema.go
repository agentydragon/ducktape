package centralsampler

// Migration 13 is a single registered Go migration. These idempotent DDL phases
// allow it to resume between bounded conversion transactions after an interruption.
const nativeContentSchema = `
CREATE TABLE IF NOT EXISTS sampler_content (
    id TEXT PRIMARY KEY,
    kind TEXT NOT NULL,
    payload BYTEA NOT NULL
);
CREATE TABLE IF NOT EXISTS sampler_context (
    id TEXT PRIMARY KEY,
    api TEXT NOT NULL CHECK (api IN ('responses', 'anthropic_messages')),
    parent_id TEXT REFERENCES sampler_context(id),
    content_id TEXT NOT NULL REFERENCES sampler_content(id),
    item_count BIGINT NOT NULL CHECK (item_count > 0)
);
ALTER TABLE sampler_conversation
    ADD COLUMN IF NOT EXISTS archive_context_id TEXT REFERENCES sampler_context(id),
    ADD COLUMN IF NOT EXISTS active_context_id TEXT REFERENCES sampler_context(id),
    ADD COLUMN IF NOT EXISTS archive_control JSONB,
    ADD COLUMN IF NOT EXISTS active_control JSONB;
CREATE TABLE IF NOT EXISTS sampler_model_request (
    id UUID PRIMARY KEY REFERENCES sampler_intent(id),
    conversation_id UUID NOT NULL REFERENCES sampler_conversation(id),
    position BIGINT GENERATED BY DEFAULT AS IDENTITY,
    context_id TEXT REFERENCES sampler_context(id),
    profile_id TEXT NOT NULL REFERENCES sampler_content(id)
);
CREATE INDEX IF NOT EXISTS sampler_model_request_latest_idx ON sampler_model_request(conversation_id,position DESC);
`

const retireInlineContentSchema = `
DROP TABLE IF EXISTS sampler_conversation_item;
ALTER TABLE sampler_conversation DROP COLUMN IF EXISTS context;
`
