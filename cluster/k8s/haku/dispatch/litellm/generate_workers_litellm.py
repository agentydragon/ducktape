"""Generates cluster/k8s/haku/dispatch/litellm/workers-litellm-config.yaml.

Run to regenerate the committed file:
    bazel run //cluster/k8s/haku/dispatch/litellm:generate_workers_litellm_bin

Parity enforced by:
    bazel test //cluster/k8s/haku/dispatch/litellm:test_generate_workers_litellm

The zone model lists come straight from the main instance's generator, so the
chained model_name entries cannot drift from what the main LiteLLM serves.
The zone-key allowlists in tf/gitops/litellm-keys/main.tf mirror the same
lists (cross-checked by the test here).
"""

import yaml

from cluster.k8s.litellm.app.generate_litellm import ZAI_ANTHROPIC_MODELS
from devinfra.prettier import prettier_format_in_place
from util.bazel.workspace import get_build_workspace_directory

_MAIN_LITELLM_BASE = "http://litellm.litellm.svc.cluster.local:4000"

_HEADER = """\
# Generated by //cluster/k8s/haku/dispatch/litellm:generate_workers_litellm_bin
# — do not edit by hand.
#
# Workers-LiteLLM proxy config (second-layer LiteLLM for Haku worker zones —
# haku/plans/multi_agent.md → key containment). Chains to the main LiteLLM via
# the litellm_proxy/ provider; the upstream credential per model group is that
# zone's static key (mounted only into this deployment). Workers authenticate
# with validator-minted per-job virtual keys whose model allowlist enforces
# their zone.
#
# oai zone models (*-chatgpt) are added when haku-sandbox-oai lands
# (build-order step 5).
#
# TODO(langfuse): point LANGFUSE_* at a dedicated haku-workers Langfuse project
# once it exists; until then only prometheus is wired.
"""


def zai_zone_model_names() -> list[str]:
    return [f"{model}-anthropic" for model in ZAI_ANTHROPIC_MODELS]


def generate() -> str:
    config = {
        "model_list": [
            {
                "model_name": name,
                "litellm_params": {
                    "model": f"litellm_proxy/{name}",
                    "api_base": _MAIN_LITELLM_BASE,
                    "api_key": "os.environ/ZAI_ZONE_KEY",
                },
            }
            for name in zai_zone_model_names()
        ],
        "litellm_settings": {"drop_params": True, "callbacks": ["prometheus"]},
        # Same rule as the main instance: the virtual-key DB must never become
        # a model source (BerriAI/litellm#28044).
        "general_settings": {"store_model_in_db": False},
    }
    return _HEADER + yaml.dump(config, default_flow_style=False, sort_keys=False, allow_unicode=True)


def main() -> None:
    out_path = get_build_workspace_directory() / "cluster/k8s/haku/dispatch/litellm/workers-litellm-config.yaml"
    out_path.write_text(generate())
    prettier_format_in_place(out_path)
    print(f"Generated {out_path}")


if __name__ == "__main__":
    main()
