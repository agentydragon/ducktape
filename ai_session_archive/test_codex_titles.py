def _index_record(title: str, *, timestamp: str = "2026-01-01T00:00:00Z") -> str:
    return json.dumps({"id": "thread-one", "thread_name": title, "updated_at": timestamp}) + "\n"


def _snapshot_sqlite(home: Path, title: str) -> None:
    codex = home / ".codex"
    staging = home / ".local/state/ducktape/ai-session-backup-sqlite"
    image = staging / "images/codex/test-root/state_5.sqlite"
    image.parent.mkdir(parents=True, exist_ok=True)
    image.unlink(missing_ok=True)
    with sqlite3.connect(image) as db:
        db.execute("CREATE TABLE threads (id TEXT, rollout_path TEXT, name TEXT, title TEXT, source TEXT)")
        db.execute(
            "INSERT INTO threads VALUES (?, ?, ?, ?, ?)",
            ("thread-one", str(codex / "sessions/2026/01/thread-one.jsonl"), title, "Autogenerated title", '"cli"'),
        )
    manifest = {
        "version": 1,
        "databases": [
            {
                "harness": "codex",
                "source": str(codex / "state_5.sqlite"),
                "image": "images/codex/test-root/state_5.sqlite",
                "sha256": hashlib.sha256(image.read_bytes()).hexdigest(),
            }
        ],
        "errors": [],
    }
    (staging / "manifest.json").write_text(json.dumps(manifest))


def _transcript(home: Path) -> Path:
    path = home / ".codex/sessions/2026/01/thread-one.jsonl"
    path.parent.mkdir(parents=True)
    path.write_text('{"type":"session_meta","payload":{"id":"thread-one"}}\n')
    return path


def test_codex_titles_from_fresh_imports(tmp_path: Path, postgres_engine: Engine) -> None:
    repository, env = _new_repository(tmp_path)
    home = Path(env["HOME"])
    codex = home / ".codex"
    _transcript(home)
    _backup(env, Path(".codex"), cwd=home)
    first_snapshot = repository.list_snapshots()[0]
    assert repository.list_files(first_snapshot.id, "/.codex/session_index.jsonl") == []
    assert (
        repository.list_files(first_snapshot.id, "/.local/state/ducktape/ai-session-backup-sqlite/manifest.json") == []
    )
    factory = sessionmaker(postgres_engine, expire_on_commit=False)
    ingestor = SnapshotIngestor(
        factory, ArchiveSource("host", "Host", repository, (HarnessRoot(Harness.CODEX, "/.codex"),))
    )
    assert ingestor.ingest().snapshots_incomplete == 0
    with factory() as db:
        assert db.scalar(select(SessionRow.title)) is None
        assert db.get(CodexTitleBackfillRow, "host") is None

    # A partially captured index must not hide the good SQLite image.
    (codex / "session_index.jsonl").write_text('{"id":"unfinished"')
    _snapshot_sqlite(home, "First name")
    _backup(env, Path(".codex"), Path(".local/state/ducktape/ai-session-backup-sqlite"), cwd=home)
    second_snapshot = repository.list_snapshots()[-1]
    report = ingestor.ingest()
    assert report.snapshots_incomplete == 0
    assert report.codex_metadata_partial == 1
    with factory() as db:
        assert db.scalar(select(SessionRow.title)) == "First name"
        assert db.get(CodexTitleBackfillRow, "host") is None
        observation = db.get(CodexTitleObservationRow, ("host", second_snapshot.id, "thread-one"))
        assert observation is not None
        assert observation.title_source == "sqlite_name"
        assert observation.source_path == ("/.codex/sessions/2026/01/thread-one.jsonl")
        assert observation.session_kind == "main"
        assert db.scalar(select(SessionRow.session_kind)) == "main"

    with factory() as db, db.begin():
        observation = db.get(CodexTitleObservationRow, ("host", second_snapshot.id, "thread-one"))
        assert observation is not None
        observation.title = "retained title"
        observation.session_kind = None
    ingestor._codex_metadata.process_snapshot(second_snapshot, refresh_completed=True)
    with factory() as db:
        observation = db.get(CodexTitleObservationRow, ("host", second_snapshot.id, "thread-one"))
        assert observation is not None
        assert observation.title == "retained title"
        assert observation.session_kind == "main"


def test_codex_title_rename_order_and_partial_index(tmp_path: Path, postgres_engine: Engine) -> None:
    repository, env = _new_repository(tmp_path)
    home = Path(env["HOME"])
    codex = home / ".codex"
    _transcript(home)
    (codex / "session_index.jsonl").write_text(_index_record("First name"))
    _snapshot_sqlite(home, "Different SQLite title")
    _backup(env, Path(".codex"), Path(".local/state/ducktape/ai-session-backup-sqlite"), cwd=home)
    first_snapshot = repository.list_snapshots()[0]
    factory = sessionmaker(postgres_engine, expire_on_commit=False)
    ingestor = SnapshotIngestor(
        factory, ArchiveSource("host", "Host", repository, (HarnessRoot(Harness.CODEX, "/.codex"),))
    )
    assert ingestor.ingest().snapshots_incomplete == 0
    with factory() as db:
        assert db.scalar(select(SessionRow.title)) == "First name"

    with (codex / "session_index.jsonl").open("a") as index:
        index.write(_index_record("Renamed", timestamp="2026-01-02T00:00:00Z"))
        index.write('{"id":"unfinished"')
    _snapshot_sqlite(home, "Renamed")
    _backup(env, Path(".codex"), Path(".local/state/ducktape/ai-session-backup-sqlite"), cwd=home)
    report = ingestor.ingest()
    assert report.snapshots_incomplete == 0
    assert report.codex_metadata_partial == 1
    with factory() as db:
        assert db.scalar(select(SessionRow.title)) == "Renamed"
        first = db.get(ResticSnapshotRow, ("host", first_snapshot.id))
        assert first is not None
        first.codex_metadata_status = "pending"
        db.commit()
    assert ingestor.ingest().snapshots_incomplete == 0
    with factory() as db:
        assert db.scalar(select(SessionRow.title)) == "Renamed"


def test_retry_updates_observation_after_index_read_recovers(tmp_path: Path, postgres_engine: Engine) -> None:
    repository, env = _new_repository(tmp_path)
    home = Path(env["HOME"])
    codex = home / ".codex"
    _transcript(home)
    (codex / "session_index.jsonl").write_text(
        _index_record("Index winner")
        + json.dumps({"id": "thread-two", "thread_name": "New on retry", "updated_at": "2026-01-01T00:00:00Z"})
        + "\n"
    )
    _snapshot_sqlite(home, "SQLite fallback")
    _backup(env, Path(".codex"), Path(".local/state/ducktape/ai-session-backup-sqlite"), cwd=home)
    snapshot = repository.list_snapshots()[0]
    factory = sessionmaker(postgres_engine, expire_on_commit=False)
    ingestor = SnapshotIngestor(
        factory, ArchiveSource("host", "Host", repository, (HarnessRoot(Harness.CODEX, "/.codex"),))
    )

    original_dump = repository.dump_to

    def fail_index(snapshot_id: str, path: str, destination: BinaryIO) -> None:
        if path == "/.codex/session_index.jsonl":
            raise ResticCommandError(("dump", snapshot_id, "--", path), 1, b"temporary read failure")
        original_dump(snapshot_id, path, destination)

    with patch.object(repository, "dump_to", side_effect=fail_index):
        assert ingestor.ingest().snapshots_incomplete == 1
    with factory() as db:
        assert db.scalar(select(SessionRow.title)) == "SQLite fallback"
        row = db.get(ResticSnapshotRow, ("host", snapshot.id))
        assert row is not None
        assert row.codex_metadata_status == "failed"
        observation = db.get(CodexTitleObservationRow, ("host", snapshot.id, "thread-one"))
        assert observation is not None
        assert observation.title_source == "sqlite_name"
        assert db.get(CodexTitleObservationRow, ("host", snapshot.id, "thread-two")) is None

    assert ingestor.ingest().snapshots_incomplete == 0
    with factory() as db:
        assert db.scalar(select(SessionRow.title)) == "Index winner"
        row = db.get(ResticSnapshotRow, ("host", snapshot.id))
        assert row is not None
        assert row.codex_metadata_status == "complete"
        observation = db.get(CodexTitleObservationRow, ("host", snapshot.id, "thread-one"))
        assert observation is not None
        assert observation.title_source == "session_index"
        new_observation = db.get(CodexTitleObservationRow, ("host", snapshot.id, "thread-two"))
        assert new_observation is not None
        assert new_observation.title == "New on retry"
        assert new_observation.title_source == "session_index"


def test_index_title_requires_unique_native_identity(tmp_path: Path, postgres_engine: Engine) -> None:
    repository, env = _new_repository(tmp_path)
    home = Path(env["HOME"])
    codex = home / ".codex"
    for relative in ("sessions/2026/01/shared.jsonl", "archived_sessions/shared.jsonl"):
        transcript = codex / relative
        transcript.parent.mkdir(parents=True, exist_ok=True)
        transcript.write_text('{"type":"session_meta","payload":{"id":"shared"}}\n')
    (codex / "session_index.jsonl").write_text(
        json.dumps({"id": "shared", "thread_name": "Ambiguous", "updated_at": "2026-01-01T00:00:00Z"}) + "\n"
    )
    _backup(env, Path(".codex"), cwd=home)
    factory = sessionmaker(postgres_engine, expire_on_commit=False)
    ingestor = SnapshotIngestor(
        factory, ArchiveSource("host", "Host", repository, (HarnessRoot(Harness.CODEX, "/.codex"),))
    )
    assert ingestor.ingest().snapshots_incomplete == 0
    with factory() as db:
        assert [row.title for row in db.scalars(select(SessionRow))] == [None, None]


