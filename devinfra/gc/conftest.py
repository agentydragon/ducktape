def _base_name(workspace: Path) -> str:
    return hashlib.md5(os.fsencode(workspace), usedforsecurity=False).hexdigest()


def make_base(root: Path, workspace: Path, *, name: str | None = None) -> Path:
    """A synthetic Bazel output base directory recording `workspace` the way a real one does."""
    base = root / (name or _base_name(workspace))
    (base / "server").mkdir(parents=True)
    (base / "lock").write_bytes(b"")
    (base / "README").write_bytes(b"WORKSPACE: " + os.fsencode(workspace) + b"\n\nGenerated by Bazel.\n")
    (base / "DO_NOT_BUILD_HERE").write_bytes(os.fsencode(workspace))
    (base / "server" / "cmdline").write_bytes(
        b"bazel(test)\0--output_base="
        + os.fsencode(base.resolve())
        + b"\0--workspace_directory="
        + os.fsencode(workspace)
    )
    return base


def cache_entry_path(contents: Path, hash_digit: str, uuid_digit: str) -> Path:
    """Expand test IDs to Bazel's hash/UUID cache layout."""
    return contents / (hash_digit * 64) / str(UUID(uuid_digit * 32))


def make_cache_entry(contents: Path, hash_digit: str, uuid_digit: str, *, recorded_inputs: bool = True) -> Path:
    """A fetched repository as Bazel's repo contents cache holds it: the directory plus its
    recorded-inputs file."""
    entry = cache_entry_path(contents, hash_digit, uuid_digit)
    entry.mkdir(parents=True)
    (entry / "REPO.bazel").write_text("")
    (entry / "payload").write_bytes(b"x" * 4096)
    if recorded_inputs:
        recorded_inputs_of(entry).write_text(f"{entry.parent.name}\n")
    return entry


def link_external(base: Path, repo: str, target: Path) -> None:
    """`<base>/external/<repo> -> target`, the way an output base uses a repo-cache entry."""
    (base / "external").mkdir(exist_ok=True)
    (base / "external" / repo).symlink_to(target)


@contextmanager
def hold_posix_lock(path: Path, mode: int, *, length: int = 0) -> Iterator[None]:
    """Hold a POSIX record lock in a separate process, as a Bazel command would."""
    script = """
import fcntl, sys

with open(sys.argv[1], "r+b") as lock:
    fcntl.lockf(lock, int(sys.argv[2]) | fcntl.LOCK_NB, int(sys.argv[3]))
    print("locked", flush=True)
    sys.stdin.read(1)
"""
    with subprocess.Popen(
        [sys.executable, "-c", script, path, str(mode), str(length)],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        text=True,
    ) as holder:
        assert holder.stdout is not None
        assert holder.stdout.readline() == "locked\n"
        try:
            yield
        finally:
            try:
                holder.communicate(timeout=5)
            except subprocess.TimeoutExpired:
                holder.kill()
                raise
