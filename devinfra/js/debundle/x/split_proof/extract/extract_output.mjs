// Front end for checking an output: bundle + a directory of .mjs files  ->  JSON facts (or Lean source).
//
//   node extract_output.mjs <bundle.mjs> <outdir> <entry.mjs>           > facts.json
//   node extract_output.mjs <bundle.mjs> <outdir> <entry.mjs> --lean    > Instance.lean
//
// From each output file it reads only: `import { a, b } from "./m.mjs"` / `import "./m.mjs"`,
// `export { a, b }`, and the verbatim text of every other top-level statement.
// Anything else (renaming imports, default/namespace imports, `export const ...`,
// re-exports, imports from outside the directory) is rejected rather than interpreted.

import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import * as acorn from "acorn";
import { footprints, leanStmtText } from "./extract.mjs";

const [bundlePath, outDir, entry, flag] = process.argv.slice(2);

function readModule(file) {
  const code = readFileSync(join(outDir, file), "utf8");
  const ast = acorn.parse(code, { ecmaVersion: "latest", sourceType: "module" });
  const mod = { name: file, imports: [], exports: [], body: [] };
  const reject = (n, why) => {
    throw new Error(`${file}: ${why}: ${code.slice(n.start, n.start + 60)}`);
  };
  for (const n of ast.body) {
    if (n.type === "ImportDeclaration") {
      const src = n.source.value;
      if (!/^\.\/[^/]+\.mjs$/.test(src)) reject(n, "import from outside the output directory");
      const names = n.specifiers.map((s) => {
        if (s.type !== "ImportSpecifier" || s.imported.name !== s.local.name)
          reject(s, "renamed, default or namespace import");
        return s.local.name;
      });
      mod.imports.push([src.slice(2), names]);
    } else if (n.type === "ExportNamedDeclaration") {
      if (n.declaration || n.source) reject(n, "export other than `export { names }`");
      for (const s of n.specifiers) {
        if (s.local.name !== s.exported.name) reject(s, "renamed export");
        mod.exports.push(s.local.name);
      }
    } else if (/^(Export|Import)/.test(n.type)) {
      reject(n, "unsupported module syntax");
    } else {
      mod.body.push(code.slice(n.start, n.end));
    }
  }
  return mod;
}

const bundle = footprints(readFileSync(bundlePath, "utf8"));
const outs = readdirSync(outDir)
  .filter((f) => f.endsWith(".mjs"))
  .sort()
  .map(readModule);

if (flag === "--lean") {
  const q = JSON.stringify;
  const list = (xs) => `[${xs.map(q).join(", ")}]`;
  const mods = outs
    .map(
      (m) =>
        `  { name := ${q(m.name)}, imports := [${m.imports.map(([s, ns]) => `(${q(s)}, ${list(ns)})`).join(", ")}], exports := ${list(m.exports)},\n    body := ${list(m.body)} }`
    )
    .join(",\n");
  process.stdout.write(`-- GENERATED by extract/extract_output.mjs. Do not edit.
import Experiments.CheckOutput
open EsmSplit

def bundle : Bundle := [
${bundle.map(leanStmtText).join(",\n")}
]

def outs : List OutModule := [
${mods}
]

/-- The confirmation: these files are a valid reshuffle of the bundle. -/
theorem output_ok : checkOutput bundle ${q(entry)} outs = true := by decide +kernel

theorem output_correct : ∃ P, Matches bundle ${q(entry)} outs P ∧ Correct bundle P := checkOutput_correct output_ok

#print axioms output_correct
`);
} else {
  process.stdout.write(JSON.stringify({ bundle, entry, outs }, null, 1) + "\n");
}
