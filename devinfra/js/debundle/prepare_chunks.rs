use std::collections::{BTreeMap, BTreeSet};

use anyhow::{Context, Result};
use rayon::prelude::*;
use swc_common::GLOBALS;

use artifact::reports::{ArtifactChunkRecord, ArtifactCounts, ChunkAnalysisReport};
use artifact::{
    CANONICAL_CHUNK_ENTRY_FILE, ChunkArtifact, ChunkBundle, ChunkMetadata, FileMetadata, FileRole,
    JsChunk, JsFile, JsFileBody, LoadedJsChunks, SourceProgram,
};
use js_ast::{ParsedJsModule, parse_js_module_consuming};
use program_analysis::{analyze_program_shallow, build_chunk_manifest_from_analysis};
use source_identity::ChunkId;
use spec::VendorMark;

const CANONICALIZE_HEADER_LINES: &[&str] = &[
    "// Generated by //devinfra/js/debundle:prepare_chunks.",
    "// Executable chunk entry.",
];

#[derive(Clone)]
pub struct SourcePreparation {
    pub program: SourceProgram,
    pub counts: ArtifactCounts,
    pub chunk_records: Vec<ArtifactChunkRecord>,
}

/// `materialized_chunk_ids` is `TransformSpec::materialize_chunk_ids`: the
/// chunks whose modules are planned keep their AST. `analysis_provider_chunk_ids`
/// independently retains original ASTs for source-premise providers, including
/// providers inside the import closure that are not materialized.
pub fn prepare_js_chunks(
    materialized_chunk_ids: &BTreeSet<String>,
    analysis_provider_chunk_ids: &BTreeSet<String>,
    vendor: &BTreeMap<String, VendorMark>,
    loaded: LoadedJsChunks,
) -> Result<SourcePreparation> {
    let LoadedJsChunks {
        chunks,
        chunk_table,
    } = loaded;

    let jobs = chunks
        .into_iter()
        .enumerate()
        .map(|(index, mut chunk)| {
            let chunk_id = ChunkId(index);
            let chunk_name = chunk_table.name(chunk_id).to_string();
            let entry_file = chunk.entry_file.clone();
            let entry_artifact_file = chunk.remove_file(&entry_file).with_context(|| {
                format!(
                    "prepare_js_chunks requires entry file for chunk: {chunk_name}/{entry_file}"
                )
            })?;
            let entry_source = entry_artifact_file.into_source().with_context(|| {
                format!("prepare_js_chunks requires content for chunk: {chunk_name}/{entry_file}")
            })?;
            Ok(PrepareChunkJob {
                chunk_id,
                chunk_name,
                entry_file,
                source_path: chunk.metadata.source_path.clone(),
                entry_source,
            })
        })
        .collect::<Result<Vec<_>>>()?;

    // First pass: parse all chunks and collect shallow manifest/rewrite facts.
    // Source text moves into the SourceMap; no extra copy.
    // Rayon workers don't inherit the caller's `swc_common::GLOBALS` scope
    // (it's `scoped_tls`, per-thread), so we re-set it inside each worker
    // closure to give `Mark::new()` an arena to mint into.
    let parsed_chunks = GLOBALS.with(|globals| {
        jobs.into_par_iter()
            .map(|job| {
                GLOBALS.set(globals, || {
                    let chunk_id = job.chunk_id;
                    let chunk_name = job.chunk_name.clone();
                    let parsed = prepare_chunk(job)?;
                    Ok((chunk_id, chunk_name, parsed))
                })
            })
            .collect::<Result<Vec<_>>>()
    })?;

    // Build set of vendor target chunk ids
    let vendor_target_chunk_ids: BTreeSet<String> = vendor
        .keys()
        .filter_map(|chunk_path| {
            // Vendor marks use .js paths, convert to chunk ids
            chunk_path.strip_suffix(".js").map(|s| s.to_string())
        })
        .collect();

    // Second pass: replace ASTs with original source for chunks that don't need them.
    //
    // A chunk needs to keep its AST if any downstream stage will read it. The
    // predicates below cover spec-driven stages (logical modules, residual
    // modules, renames, vendor) and source-premise provider analysis. The
    // pass-through emission rewriter also canonicalizes specifiers in every
    // emitted non-module file, so we keep its AST whenever it would rewrite this
    // chunk's entry. The `has_rewritable_specifier` fact mirrors the
    // canonicalizer's relative-path gate (`.` or `/` prefix) exactly and is
    // computed during the first-pass `analyze_program_shallow` walk, so this
    // second pass does not need to re-visit the AST.
    let prepared_chunks = parsed_chunks
        .into_iter()
        .map(|(chunk_id, chunk_name, mut prepared)| {
            let needs_emission_ast = materialized_chunk_ids.contains(&chunk_name)
                || vendor_target_chunk_ids.contains(&chunk_name)
                || prepared.has_rewritable_specifier;

            if !needs_emission_ast
                && let Some(pos) = prepared
                    .files
                    .iter()
                    .position(|f| f.path == CANONICAL_CHUNK_ENTRY_FILE)
            {
                let file = prepared.files.remove(pos);
                // Read-only analysis retention must not change source-marker
                // matching or pass-through output bytes/header behavior.
                let file = if analysis_provider_chunk_ids.contains(&chunk_name) {
                    file.into_source_with_ast()
                } else {
                    file.into_rendered_source()
                }
                .context("freshly prepared entry must contain an AST")?;
                prepared.files.insert(pos, file);
            }

            Ok((chunk_id, chunk_name, prepared))
        })
        .collect::<Result<Vec<_>>>()?;

    let artifact = ChunkBundle {
        chunks: prepared_chunks
            .into_iter()
            .map(|(chunk_id, _, prepared)| ChunkArtifact {
                chunk_id,
                js: JsChunk {
                    entry_file: CANONICAL_CHUNK_ENTRY_FILE.to_string(),
                    files: prepared.files,
                    metadata: prepared.metadata,
                },
                analysis: prepared.analysis,
            })
            .collect(),
        chunk_table,
    };

    let (counts, chunk_records) = build_prepare_output(&artifact.chunks);
    Ok(SourcePreparation {
        program: SourceProgram::new(artifact)?,
        counts,
        chunk_records,
    })
}

struct PrepareChunkJob {
    chunk_id: ChunkId,
    chunk_name: String,
    entry_file: String,
    source_path: String,
    entry_source: String,
}

struct PreparedChunk {
    files: Vec<JsFile>,
    metadata: ChunkMetadata,
    analysis: ChunkAnalysisReport,
    /// Captured from the fused `analyze_program_shallow` walk so the
    /// second pass can decide AST retention without re-visiting the
    /// AST.
    has_rewritable_specifier: bool,
}

fn prepare_chunk(job: PrepareChunkJob) -> Result<PreparedChunk> {
    let parsed = parse_js_module_consuming(
        &format!("{}/{}", job.chunk_name, job.entry_file),
        job.entry_source,
    )?;
    let analysis = analyze_program_shallow(&parsed);
    Ok(PreparedChunk {
        files: vec![canonical_parsed_file(
            &job.chunk_name,
            &job.source_path,
            parsed,
        )],
        analysis: build_chunk_manifest_from_analysis(
            &job.chunk_name,
            CANONICAL_CHUNK_ENTRY_FILE,
            &job.source_path,
            &analysis,
        ),
        has_rewritable_specifier: analysis.has_rewritable_specifier,
        metadata: ChunkMetadata {
            source_path: job.source_path,
        },
    })
}

fn canonical_parsed_file(chunk_id: &str, source_path: &str, parsed: ParsedJsModule) -> JsFile {
    JsFile {
        path: CANONICAL_CHUNK_ENTRY_FILE.to_string(),
        body: JsFileBody::Ast(parsed),
        header_lines: CANONICALIZE_HEADER_LINES
            .iter()
            .map(|line| (*line).to_string())
            .collect(),
        binding_comments: BTreeMap::new(),
        leading_item_comments: BTreeMap::new(),
        metadata: FileMetadata {
            chunk_id: chunk_id.to_string(),
            chunk_file: CANONICAL_CHUNK_ENTRY_FILE.to_string(),
            role: FileRole::Entry,
            source_path: source_path.to_string(),
        },
    }
}

fn build_prepare_output(chunks: &[ChunkArtifact]) -> (ArtifactCounts, Vec<ArtifactChunkRecord>) {
    let mut counts = ArtifactCounts {
        kept_top_level_declarations: 0,
        top_level_side_effects: 0,
        export_aliases: 0,
        unresolved_exports: 0,
    };
    let mut chunk_records = Vec::with_capacity(chunks.len());
    for chunk in chunks {
        let analysis = &chunk.analysis;
        counts.kept_top_level_declarations += analysis.counts.kept_top_level_declarations;
        counts.top_level_side_effects += analysis.counts.top_level_side_effects;
        counts.export_aliases += analysis.counts.export_aliases;
        counts.unresolved_exports += analysis.counts.unresolved_exports;
        chunk_records.push(ArtifactChunkRecord {
            chunk_id: analysis.chunk_id.clone(),
            source_path: analysis.source_path.clone(),
        });
    }
    (counts, chunk_records)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn source_premise_provider_retention_is_independent_of_materialization() {
        js_ast::with_swc_globals(|| {
            let root = tempfile::TempDir::new().unwrap();
            let source = "// original parser input\nexport function reader() { return 7; }\n";
            fs::write(root.path().join("provider.js"), source).unwrap();
            fs::write(root.path().join("neighbor.js"), "export const value = 7;").unwrap();
            let list = root.path().join("js-files.txt");
            fs::write(&list, "provider.js\nneighbor.js\n").unwrap();
            let spec: spec::TransformSpec = serde_yaml::from_str(concat!(
                "inputs: {input_root: '.', js_list_path: js-files.txt}\n",
                "chunk_analysis_options:\n",
                "  provider:\n",
                "    no_accessor_install_callables:\n",
                "      - source_match:\n",
                "          match: 'export function reader() { return 7; }'\n",
                "          bindings: [reader]\n",
            ))
            .unwrap();
            assert!(spec.materialize_chunk_ids().is_empty());
            let providers = spec.source_premise_chunk_ids();
            assert_eq!(providers, BTreeSet::from(["provider".to_string()]));
            for retain_provider in [false, true] {
                let loaded = artifact::load_js_chunks(root.path(), &list).unwrap();
                let retained = if retain_provider {
                    providers.clone()
                } else {
                    BTreeSet::new()
                };
                let prepared = prepare_js_chunks(
                    &spec.materialize_chunk_ids(),
                    &retained,
                    &spec.vendor,
                    loaded,
                )
                .unwrap();
                let artifact = prepared.program.artifact();
                for chunk in &artifact.chunks {
                    let name = artifact.chunk_table.name(chunk.chunk_id);
                    let file = chunk.js.get_file(CANONICAL_CHUNK_ENTRY_FILE).unwrap();
                    assert_eq!(
                        file.ast().is_some(),
                        retain_provider && name == "provider",
                        "{name}"
                    );
                    if let Some(parsed) = file.ast() {
                        assert_eq!(parsed.source_text(), source);
                        assert_eq!(file.source(), Some(source));
                        assert_eq!(file.render_source().unwrap(), source);
                        let mut mutated = file.clone();
                        mutated.ast_mut().unwrap().module.body.clear();
                        assert!(mutated.source().is_none());
                        assert!(!mutated.render_source().unwrap().contains("reader"));
                        assert_eq!(file.render_source().unwrap(), source);
                        let (parts, mut parsed) = file.clone().into_ast_parts().unwrap();
                        parsed.module.body.clear();
                        let reconstructed = JsFile::from_ast_parts(parts, parsed);
                        assert!(reconstructed.source().is_none());
                        assert!(!reconstructed.render_source().unwrap().contains("reader"));
                    }
                }
                // Both source-to-emission paths restore pass-through source
                // storage before eager mutation passes can enroll the provider.
                let emissions = [
                    artifact::EmissionFiles::new(artifact.clone()).unwrap(),
                    artifact::EmissionFiles::from_prepared(prepared.program),
                ];
                for emission in emissions {
                    for chunk in &emission.files().chunks {
                        let name = emission.files().chunk_table.name(chunk.chunk_id);
                        let file = chunk.js.get_file(CANONICAL_CHUNK_ENTRY_FILE).unwrap();
                        assert!(file.ast().is_none(), "{name}");
                        if name == "provider" {
                            assert_eq!(file.render_source().unwrap(), source);
                        }
                    }
                }
            }
        });
    }

    // Retention is an internal storage invariant, not observable in emitted JS.
    // Load real source files through the normal loader and fused preparation.
    #[test]
    fn vendor_neighbors_retain_ast_only_for_their_own_work() {
        js_ast::with_swc_globals(|| {
            let root = tempfile::TempDir::new().unwrap();
            for (name, source) in [
                (
                    "vendor.js",
                    "import { helper } from './helper.js'; export const value = helper();",
                ),
                ("helper.js", "export const helper = () => 7;"),
                (
                    "caller.js",
                    "import { value } from './vendor.js'; console.log(value);",
                ),
                ("forward.js", "export { value } from './vendor.js';"),
                (
                    "dynamic.js",
                    "export const load = () => import('./vendor.js');",
                ),
            ] {
                fs::write(root.path().join(name), source).unwrap();
            }
            let list = root.path().join("js-files.txt");
            fs::write(
                &list,
                "vendor.js\nhelper.js\ncaller.js\nforward.js\ndynamic.js\n",
            )
            .unwrap();
            let spec: spec::TransformSpec = serde_yaml::from_str(
                "inputs: {input_root: '.', js_list_path: js-files.txt}\nvendor:\n  vendor.js: {identity: fixture, level: suppress}\n",
            ).unwrap();
            let loaded = artifact::load_js_chunks(root.path(), &list).unwrap();
            let prepared = prepare_js_chunks(
                &spec.materialize_chunk_ids(),
                &spec.source_premise_chunk_ids(),
                &spec.vendor,
                loaded,
            )
            .unwrap();
            let emission = artifact::EmissionFiles::from_prepared(prepared.program.clone());
            for artifact in [prepared.program.artifact(), emission.files()] {
                for chunk in &artifact.chunks {
                    let name = artifact.chunk_table.name(chunk.chunk_id);
                    let has_ast = chunk
                        .js
                        .get_file(CANONICAL_CHUNK_ENTRY_FILE)
                        .unwrap()
                        .ast()
                        .is_some();
                    assert_eq!(has_ast, name != "helper", "{name}");
                }
            }
        });
    }
}
